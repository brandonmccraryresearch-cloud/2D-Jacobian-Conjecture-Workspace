# ------------------------------------------------------------------ generic: parts of sum_j m_j * S_j
def parts_lemmas(prefix, path, mults, polys, rnames, extra_vars, target, render=None):
    render = render or (lambda j: poly(polys[j]))
    """target(=value identity or condition) == sum_j m_j * polys[j]; emit part lemmas with work <= BUDGET.
       mults: list of fmpq_poly (K5) or None; returns (list of (lemma name, module, hyps used, part poly))."""
    idx = [j for j, m in enumerate(mults) if m is not None and m != 0]
    groups, cur, cw = [], [], 0
    for j in idx:
        wj = 5 * max(1, sum(sum(1 for i in range(5) if c[i] != 0) for c in polys[j].values()))
        if cur and cw + wj > BUDGET: groups.append(cur); cur, cw = [], 0
        cur.append(j); cw += wj
    if cur: groups.append(cur)
    out, total = [], {}
    for n, g in enumerate(groups, 1):
        P = {}
        for j in g: P = P_add(P, P_scale(polys[j], mults[j]))
        total = P_add(total, P)
        name = f"{prefix}_p{n}"
        binders = B_W + B_vars(PARAMS + extra_vars) + [f"({rnames[j]} : {render(j)} = 0)" for j in g]
        lc = " + ".join(f"{kel(mults[j])} * {rnames[j]}" for j in g)
        body = HWLEM + [f"  linear_combination (norm := skip) {lc}", f"  {CLOSE}"]
        w = sum(5 * max(1, sum(sum(1 for i in range(5) if c[i] != 0) for c in polys[j].values())) for j in g)
        mod = put(f"{path}_p{n}", lemma(name, binders, f"{poly(P)} = 0", body), work=w)
        out.append((name, mod, [rnames[j] for j in g], P))
    assert P_add(total, target, -1) == {}, prefix          # exact: sum of parts == target
    return out

