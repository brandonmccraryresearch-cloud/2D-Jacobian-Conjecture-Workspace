# ------------------------------------------------------------------ Lean rendering (as gen_lean_c.py)
def q(s):
    f = Fraction(s)
    if f.denominator == 1: return f"({f.numerator} : L)"
    return f"(({f.numerator}) / {f.denominator} : L)"
def kel_s(c):
    terms = []
    for i, s in enumerate(c):
        if Fraction(s) == 0: continue
        terms.append(q(s) + ("" if i == 0 else (" * w" if i == 1 else f" * w ^ ({i} : ℕ)")))
    return "(" + (" + ".join(terms) if terms else "(0 : L)") + ")"
def kel(a): return kel_s([str(a[i]) for i in range(5)])            # fmpq_poly -> Lean
def mono(m): return " * ".join(v if e == 1 else f"{v} ^ ({e} : ℕ)" for v, e in m)
def poly(p):                                                          # dict poly -> Lean
    if not p: return "(0 : L)"
    return "(" + " + ".join(kel(c) + (" * " + mono(m) if m else "") for m, c in sorted(p.items())) + ")"
def poly_pj(p):                                                       # exactly gen_lean_c.poly (list order)
    if not p: return "(0 : L)"
    return "(" + " + ".join(kel_s(c) + (" * " + mono(m) if m else "") for m, c in p) + ")"
