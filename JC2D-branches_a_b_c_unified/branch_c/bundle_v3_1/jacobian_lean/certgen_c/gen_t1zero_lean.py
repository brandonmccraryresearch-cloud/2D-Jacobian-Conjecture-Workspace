def tgt_expr(t):
    if isinstance(t, tuple) and t[0] == "X2": return f"(Expr.mul (.num {t[1]}) (Expr.pow eX 2))"
    if isinstance(t, tuple) and t[0] == "num": return f"(Expr.num {t[1]})"
    return t
def cost(a, b): return a * (b + a * b)                        # mulK with a first factor of a terms (rough bound)
EST = {}
def thm(name, t, cl, doc):
    l1, l2, est = [], [], 0
    for m, f in cl:
        if not m: continue
        nf = len(facts[f])
        if len(m) <= nf: l1.append((m, f)); est += cost(len(m), nf)
        else: l2.append((m, f)); est += cost(nf, len(m))
    EST[name] = est
    hyps = " ".join(f"(h_{fn(f)} : {fn(f)}.denote ctx = 0)" for m, f in cl if m)
    s1 = ", ".join(f"({pe(m)}, {fn(f)})" for m, f in l1)
    s2 = ", ".join(f"({pe(m)}, {fn(f)})" for m, f in l2)
    a1 = ("⟨" + "".join(f"h_{fn(f)}, " for m, f in l1) + "trivial⟩") if l1 else "trivial"
    a2 = ("⟨" + "".join(f"h_{fn(f)}, " for m, f in l2) + "trivial⟩") if l2 else "trivial"
    return (f"/-- {doc} -/\ntheorem {name} (ctx : Context α) {hyps} :\n    {tgt_expr(t)}.denote ctx = 0 :=\n"
            f"  lc_zero2 ctx {tgt_expr(t)} [{s1}] [{s2}] (by decide +kernel) {a1} {a2}\n")

