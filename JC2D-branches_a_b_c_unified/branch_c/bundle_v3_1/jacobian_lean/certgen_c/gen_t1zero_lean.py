def term_expr(key, c):                                        # = gen_refl_c.term_expr
    m, i = key; out = f"(.num ({c}))"
    fs = ([("w", i)] if i else []) + list(m)
    for v, e in fs: out = f"(.mul {out} {'(.var %d)' % IDX[v] if e == 1 else '(.pow (.var %d) %d)' % (IDX[v], e)})"
    return out
def term_lean(key, c):                                        # = gen_refl_c.term_lean (mirror of Expr.denote)
    m, i = key; out = f"({c} : L)"
    fs = ([("w", i)] if i else []) + list(m)
    for v, e in fs: out = f"({out} * {v if e == 1 else '%s ^ %d' % (v, e)})"
    return out
def balanced(ts, op_):
    if not ts: return None
    while len(ts) > 1: ts = [op_(ts[j], ts[j + 1]) if j + 1 < len(ts) else ts[j] for j in range(0, len(ts), 2)]
    return ts[0]
def pe(P): return balanced([term_expr(k, v) for k, v in sorted(P.items(), key=repr)], lambda a, b: f"(.add {a} {b})") or "(.num 0)"
def pl(P): return balanced([term_lean(k, v) for k, v in sorted(P.items(), key=repr)], lambda a, b: f"({a} + {b})") or "(0 : L)"

