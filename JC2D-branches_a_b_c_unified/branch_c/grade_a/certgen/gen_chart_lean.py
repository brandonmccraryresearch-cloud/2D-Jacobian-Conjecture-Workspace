"""
gen_chart_lean.py -- writes grade_a/lean/GradeA/Chart/{Gens,F_<n>,Main}.lean from gen_chart.py (imported: every
certificate is re-checked there by exact integer arithmetic before anything is written).

Modules (namespace BranchC.GradeA.Chart):
  Gens      tl_n : List Term (the chart generator f_n, term by term) and F_n := exprOfTerms tl_n   (GradeA.Chart.Terms)
  F_<n>     s_F_n : ck_n, eT2, eX, eR vanish  ->  F_n vanishes            (lc_zero2 + decide +kernel, as the bundle)
  Main      chart_gens_vanish (chartCtx is in Terms.lean): from the hypotheses of ChartEmptyC_T1ne0 (only R(w) = 0, b_12_22 = 1,
            Omega and the six conditions are used), the six chart generators vanish at the chart point.
The certificates have the form of the bundle's s_f_<n> (Jacobian/BranchC/T1Zero/F_<n>.lean) without the stratum
b_11_20 = 0; ck_n, eT2, eX, eR, s_sq, s_X2, cancel_int, lc_zero2 are the bundle's (Jacobian.BranchC.T1Zero.Defs, .Sq).
The printers term_expr, term_lean, balanced, pe, pl and the l1/l2 split of thm() are those of the bundle's
certgen_c/gen_t1zero_lean.py.
Environment: WRITE=0 checks without writing; ODIR=dir writes dir/GradeA/Chart/*.lean instead of ../lean.
"""
import os, sys
sys.dont_write_bytecode = True
sys.set_int_max_str_digits(0)
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import gen_chart as G

C = G.C
V, IDX, facts, NAMES, EK = C.V, C.IDX, C.facts, C.NAMES, C.EK
Dk, DO, cB = C.Dk, C.DO, C.cB
gens, certs = G.gens, G.certs
POS = G.POS                                                   # b_11_20 b_11_21 a_6_13 a_7_15 b_10_21 -> 0..4

def term_expr(key, c):                                        # = gen_t1zero_lean.term_expr
    m, i = key; out = f"(.num ({c}))"
    fs = ([("w", i)] if i else []) + list(m)
    for v, e in fs: out = f"(.mul {out} {'(.var %d)' % IDX[v] if e == 1 else '(.pow (.var %d) %d)' % (IDX[v], e)})"
    return out
def term_lean(key, c):                                        # = gen_t1zero_lean.term_lean
    m, i = key; out = f"({c} : L)"
    fs = ([("w", i)] if i else []) + list(m)
    for v, e in fs: out = f"({out} * {v if e == 1 else '%s ^ %d' % (v, e)})"
    return out
def balanced(ts, op_):
    if not ts: return None
    while len(ts) > 1: ts = [op_(ts[j], ts[j + 1]) if j + 1 < len(ts) else ts[j] for j in range(0, len(ts), 2)]
    return ts[0]
def pe(P): return balanced([term_expr(k, v) for k, v in sorted(P.items(), key=repr)], lambda a, b: f"(.add {a} {b})") or "(.num 0)"
def pl(P): return balanced([term_lean(k, v) for k, v in sorted(P.items(), key=repr)], lambda a, b: f"({a} + {b})") or "(0 : L)"

RN = {"ek_" + n: "ck_" + n for n in ["Omega"] + NAMES}
def fn(f): return RN.get(f, f)

def term_list(P):
    out = []
    for (m, i), c in sorted(P.items(), key=repr):
        e5 = [0] * 5
        for v, e in m: e5[POS[v]] += e
        out.append(f"⟨{c}, {i}, {e5[0]}, {e5[1]}, {e5[2]}, {e5[3]}, {e5[4]}⟩")
    return "[" + ",\n    ".join(out) + "]"

NS = "BranchC.GradeA.Chart"
HDR = """/-! Generated by grade_a/certgen/gen_chart_lean.py ({doc}).  Branch (c), the chart `b₁₂,₂₂ = 1`, `b₁₂,₂₃ = κ(w)` with
`b₁₁,₂₀` free: every polynomial identity is checked by the Lean kernel (`decide +kernel`, no `native_decide`) and was
checked in Python by exact integer arithmetic (grade_a/certgen/gen_chart.py) before emission.  No `sorry`. -/

set_option maxHeartbeats 0
set_option maxRecDepth 1000000
set_option linter.unusedVariables false

namespace {ns}
open {opens}

variable {{α : Type*}} [CommRing α]
"""
files = {}
def emit(mod, imports, doc, body, opens="Lean.Grind.CommRing BranchAb.ChartProof BranchC.T1Zero"):
    files[mod] = "\n".join(f"import {i}" for i in imports) + "\n\n" + HDR.format(doc=doc, ns=NS, opens=opens) + "\n" + \
        "\n".join(body) + f"\nend {NS}\n"

# ---- Gens: the term lists and the generators
body = []
for n in NAMES:
    d, f = gens[n]
    body.append(f"/-- The chart generator `{n}`: `{Dk}^{d}·ck_{n}` on `b₁₂,₂₂ = 1`, `b₁₂,₂₃ = κ(w)`, reduced mod `R`; "
                f"{len(f)} terms. -/\nnoncomputable def tl_{n} : List Term :=\n  {term_list(f)}\n")
    body.append(f"noncomputable def F_{n} : Expr := exprOfTerms tl_{n}\n")
emit("GradeA.Chart.Gens", ["GradeA.Chart.Terms"], "the six chart generators", body,
     opens="Lean.Grind.CommRing BranchAb.ChartProof")

# ---- F_<n>: the certificates (thm() of gen_t1zero_lean.py, target F_<n>)
def cost(a, b): return a * (b + a * b)
EST = {}
def thm(name, target, tpoly, cl, doc):
    l1, l2, est = [], [], 0
    for m, f in cl:
        if not m: continue
        nf = len(facts[f])
        if len(m) <= nf: l1.append((m, f)); est += cost(len(m), nf)
        else: l2.append((m, f)); est += cost(nf, len(m))
    EST[name] = est
    hyps = " ".join(f"(h_{fn(f)} : {fn(f)}.denote ctx = 0)" for m, f in cl if m)
    s1 = ", ".join(f"({pe(m)}, {fn(f)})" for m, f in l1)
    s2 = ", ".join(f"({pe(m)}, {fn(f)})" for m, f in l2)
    a1 = ("⟨" + "".join(f"h_{fn(f)}, " for m, f in l1) + "trivial⟩") if l1 else "trivial"
    a2 = ("⟨" + "".join(f"h_{fn(f)}, " for m, f in l2) + "trivial⟩") if l2 else "trivial"
    return (f"/-- {doc} -/\ntheorem {name} (ctx : Context α) {hyps} :\n    {target}.denote ctx = 0 :=\n"
            f"  lc_zero2 ctx {target} [{s1}] [{s2}] (by decide +kernel) {a1} {a2}\n")

for n in NAMES:
    d, f = gens[n]
    emit(f"GradeA.Chart.F_{n}", ["Jacobian.BranchC.T1Zero.Defs", "GradeA.Chart.Gens"], f"{n} on the chart",
         [thm(f"s_F_{n}", f"F_{n}", f, certs[n],
              f"`{n}` on `b₁₂,₂₂ = 1`, `b₁₂,₂₃ = κ(w)` (`b₁₁,₂₀` free): `{Dk}^{d}·ck_{n} = {Dk}^{d}·eT2·A + eX·B + F_{n} + "
              f"eR·C`")])

# ---- Main
cond_args = " ".join(V)
hy = [f"(c_{n} : cond_{n} {cond_args} = 0)" for n in ["Omega"] + NAMES]
concl = " ∧ ".join(f"F_{n}.denote ctx = 0" for n in NAMES)
proof = ["  intro ctx",
         "  have f_eR : eR.denote ctx = 0 := hw",
         f"  have f_eT2 : eT2.denote ctx = 0 := by\n    have h : {pl(facts['eT2'])} = 0 := by rw [ht2]; ring\n    exact h"]
proof += [f"  have f_ck_{n} : ck_{n}.denote ctx = 0 := c_{n}" for n in ["Omega"] + NAMES]
proof += ["  have f_e_sq := s_sq ctx f_ck_Omega f_eT2 f_eR",
          f"  have hX2 : (Expr.pow eX 2).denote ctx = 0 :=\n    cancel_int ctx (Expr.pow eX 2) {cB * DO} (by decide) (s_X2 ctx f_e_sq f_eR)",
          "  have hX2' : eX.denote ctx ^ 2 = 0 := hX2",
          "  have f_eX : eX.denote ctx = 0 := (pow_eq_zero_iff two_ne_zero).mp hX2'",
          "  exact ⟨" + ", ".join(f"s_F_{n} ctx f_ck_{n} f_eT2 f_eX f_eR" for n in NAMES) + "⟩"]
main = f"""/-- **The chart reduction (step A2.0).**  At a root `w` of `R`, a point with `b₁₂,₂₂ = 1` at which `Ω` and the six
conditions `Ψ, Φ₁, Φ₂, Θ₁, Θ₂, Θ₃` of lower_c vanish (Jacobian/BranchC/CondsC.lean) is a common zero of the six chart
generators `F_n` (`b₁₁,₂₀` free; `Ω` gives `b₁₂,₂₃ = κ(w)` through the bundle's `s_sq`, `s_X2`). -/
theorem chart_gens_vanish {{L : Type*}} [Field L] [CharZero L] (w : L)
    (hw : w ^ 5 - w ^ 4 + 3 * w ^ 3 + 3 * w ^ 2 + 26 = 0)
    ({' '.join(V[1:])} : L) (ht2 : b_12_22 = 1)
    {chr(10).join('    ' + h for h in hy).lstrip()} :
    let ctx := chartCtx {cond_args}
    {concl} := by
""" + "\n".join(proof) + "\n"
emit("GradeA.Chart.Main", ["Jacobian.BranchC.CondsC", "Jacobian.BranchC.T1Zero.Sq"] +
     [f"GradeA.Chart.F_{n}" for n in NAMES], "the chart reduction", [main])

ODIR = os.environ.get("ODIR") or os.path.normpath(os.path.join(HERE, "..", "lean"))   # ODIR: write elsewhere (build_chart.sh)
if os.environ.get("WRITE", "1") == "1":
    os.makedirs(os.path.join(ODIR, "GradeA", "Chart"), exist_ok=True)
    for mod, txt in files.items():
        with open(os.path.join(ODIR, *mod.split(".")) + ".lean", "w") as fh: fh.write(txt)
for mod, txt in files.items(): print(f"  {mod}: {len(txt)} bytes")
print("merge-work estimates:", EST)
