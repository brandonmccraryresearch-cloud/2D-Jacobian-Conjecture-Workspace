def lean_coef(c):
    c = sp.Rational(c)
    if c.q == 1:
        return f"({c.p})" if c.p < 0 else f"{c.p}"
    return f"({c.p}/{c.q})"


def lean_poly(e, gens):
    e = sp.expand(e)
    if e == 0:
        return "0"
    P = sp.Poly(e, *gens)
    parts = []
    for mon, c in P.terms():
        fs = []
        for v, k in zip(gens, mon):
            if k == 1:
                fs.append(str(v))
            elif k > 1:
                fs.append(f"{v}^{k}")
        if not fs:
            parts.append(lean_coef(c))
        elif c == 1:
            parts.append(" * ".join(fs))
        else:
            parts.append(lean_coef(c) + " * " + " * ".join(fs))
    return " + ".join(parts)


def read_lift(fn, gens):
    loc = {str(g): g for g in gens}
    d = {}
    for line in open(fn):
        j, i, p = line.rstrip("\n").split("|", 2)
        d[(int(j), int(i))] = sp.expand(sp.sympify(p.replace("^", "**"), locals=loc))
    return d


def chart_data(m):
    """E_N (N = 1 .. n+m) as bilinear expressions in a_1..a_{m-1}, b_1..b_n; B_k(a); residual polynomials."""
    n = (3 * m - 1) // 2
    a, A, Bk, R = chart_residuals(m)
    b = sp.symbols(f"b1:{n + 1}")
    beta = [sp.Integer(1)] + list(b)
    E = {}
    for N in range(1, n + m + 1):
        E[N] = sp.expand(sum((1 + 2 * k - 3 * (N - k)) * A[N - k] * beta[k] for k in range(0, n + 1) if 0 <= N - k <= m))
    return a, b, A, Bk, R, E, n


