"""gen_b26_lean.py -- writes B26.lean: the m = 3 and m = 5 top-layer chart systems (B2.6), classified over any field
of characteristic 0, with every step a `linear_combination` whose cofactors are explicit (Singular lift, checked in
Singular's own ring and again here with sympy before they are written).

Inputs (this directory): lift_S_to_J.txt, lift_J_to_S.txt (m = 5), m3_lift_S_to_J.txt, m3_lift_J_to_S.txt (m = 3),
the residuals r0..r3 copied from the repository's scripts/b26_m5_eliminant/m5_b2_6_eliminate_basis.sing (A816 env var
not needed).  usage: python3 gen_b26_lean.py RESIDUALS.sing OUT.lean"""
